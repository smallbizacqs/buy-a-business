#!/usr/bin/env node
// Generates README.md, llms.txt, .claude-plugin/{plugin,marketplace}.json and gemini-extension.json
// from data/taxonomy.yaml and the skills found by walking skills/. `--check` fails if any file is stale.
import { readFileSync, writeFileSync, readdirSync, existsSync, statSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';
import { parseFrontmatter } from './validate.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const RAW = 'https://raw.githubusercontent.com/smallbizacqs/buy-a-business/main';
const REPO = 'https://github.com/smallbizacqs/buy-a-business';
const AUTHOR = { name: 'Small Biz Acquisitions', email: 'support@smallbizacqs.com', url: 'https://smallbizacqs.com' };
const version = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).version;

const tax = YAML.parse(readFileSync(join(ROOT, 'data/taxonomy.yaml'), 'utf8'));
const skillsDir = join(ROOT, 'skills');
const skills = (existsSync(skillsDir) ? readdirSync(skillsDir) : [])
  .filter((d) => existsSync(join(skillsDir, d, 'SKILL.md')) && statSync(join(skillsDir, d)).isDirectory())
  .sort()
  .map((d) => ({ dir: d, ...parseFrontmatter(readFileSync(join(skillsDir, d, 'SKILL.md'), 'utf8')).data }));
const byName = new Map(skills.map((s) => [s.name, s]));
const guideFile = (s) => `guide/${String(s.order).padStart(2, '0')}-${s.id}.md`;
const firstSentence = (d) => String(d ?? '').replace(/\s+/g, ' ').split(/(?<=\.)\s/)[0];
const useWhen = (d) => { const m = String(d ?? '').replace(/\s+/g, ' ').match(/Use (when|for)[^.]*\./); return m ? m[0] : ''; };

const entry = (tax.extra_skills ?? []).filter((x) => x.kind === 'entry').map((x) => x.skill);
const stageSkills = (stageId) => {
  const names = tax.topics.filter((t) => t.stage === stageId && t.skill).map((t) => t.skill);
  for (const x of tax.extra_skills ?? []) {
    if (x.covers === 'router') continue;
    const leaf = tax.leaves.find((l) => l.id === x.covers);
    const topic = tax.topics.find((t) => t.id === leaf?.topic);
    if (topic?.stage === stageId) names.push(x.skill);
  }
  return names;
};

// ---- README
const stagesTable = tax.stages.map((s) => `| ${s.order} | ${s.title} | [\`${guideFile(s)}\`](${guideFile(s)}) |`).join('\n');
let catalog = '### Start here\n\n| Skill | What it does |\n|---|---|\n';
catalog += entry.map((n) => byName.get(n) ? `| [\`${n}\`](skills/${n}/SKILL.md) | ${firstSentence(byName.get(n).description)} |` : `| \`${n}\` | coming |`).join('\n') + '\n';
for (const s of tax.stages) {
  catalog += `\n### ${s.order}. ${s.title}\n\n| Skill | Use it when |\n|---|---|\n`;
  catalog += stageSkills(s.id).map((n) => byName.get(n) ? `| [\`${n}\`](skills/${n}/SKILL.md) | ${useWhen(byName.get(n).description).replace(/^Use (when|for) /, '') || firstSentence(byName.get(n).description)} |` : `| \`${n}\` | coming |`).join('\n') + '\n';
}
const readme = readFileSync(join(ROOT, 'README.template.md'), 'utf8')
  .replace('<!-- STAGES -->', stagesTable).replace('<!-- CATALOG -->', catalog.trim())
  .replace(/^/, '<!-- Generated by scripts/generate.mjs from README.template.md. Edit the template. -->\n');

// ---- llms.txt
const answered = tax.leaves.filter((l) => existsSync(join(ROOT, 'data/leaves', `${l.id}.md`)));
const llms = `# Buy a business

> A guide to buying a small business (entrepreneurship through acquisition, ETA, search funds, self-funded search, SBA 7(a) acquisitions), plus agent skills. Ten stages, about ${tax.leaves.length} question-shaped topics, answers with dated primary sources, practitioner clips, and one skill per topic. Human version: https://smallbizacqs.com. Install the skills: \`npx skills add smallbizacqs/buy-a-business\`.

Start with ${RAW}/AGENTS.md. Nothing here is legal, tax or financial advice.

## Stages
${tax.stages.map((s) => `- [${s.order}. ${s.title}](${RAW}/${guideFile(s)}): ${s.summary}`).join('\n')}

## Skills
${skills.map((s) => `- [${s.name}](${RAW}/skills/${s.dir}/SKILL.md): ${firstSentence(s.description)}`).join('\n')}

## Answered questions
${answered.map((l) => `- [${l.question}](${RAW}/data/leaves/${l.id}.md)`).join('\n')}

## Data
- [Taxonomy: stages, topics, questions, facets](${RAW}/data/taxonomy.yaml)
- [Glossary](${RAW}/data/glossary.yaml)
- [Workspace spec](${RAW}/workspace/SPEC.md)
`;

// ---- Claude plugin marketplace: one plugin per stage + the whole set
const present = (names) => names.filter((n) => byName.has(n)).map((n) => `./skills/${n}`);
const plugins = [
  { name: 'buy-a-business', description: 'Every skill: the guide to buying a small business, from deciding to buy to selling later.', source: './', strict: false, skills: present([...entry, ...tax.stages.flatMap((s) => stageSkills(s.id))]) },
  ...tax.stages.map((s) => ({ name: `stage-${s.order}-${String(s.short ?? s.id).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}`, description: `Stage ${s.order}: ${s.title}. ${s.summary}`, source: './', strict: false, skills: present([...entry, ...stageSkills(s.id)]) })),
].filter((p) => p.skills.length);
const marketplace = { name: 'buy-a-business', owner: AUTHOR, metadata: { description: 'A guide to buying a small business, plus agent skills.', version }, plugins };
const plugin = { name: 'buy-a-business', displayName: 'Buy a Business', version, description: 'A guide to buying a small business, plus agent skills: ten stages from deciding to buy to selling later.', author: AUTHOR, homepage: 'https://smallbizacqs.com', repository: REPO, license: 'CC-BY-4.0 AND MIT', keywords: ['buy a business', 'small business acquisition', 'entrepreneurship through acquisition', 'ETA', 'search fund', 'SBA 7(a)', 'due diligence', 'LOI'] };
const gemini = { name: 'buy-a-business', version, description: 'A guide to buying a small business, plus agent skills.', contextFileName: 'AGENTS.md' };

// ---- the router's stage map (skills/buy-a-business/references/stage-map.md)
const stageMap = `# Stage map

Generated by \`scripts/generate.mjs\` from \`data/taxonomy.yaml\`. Don't edit by hand; if the taxonomy has changed since, trust the taxonomy.

| # | Stage id | Stage | Guide page | Topic id | Topic | Skill |
|---|---|---|---|---|---|---|
${tax.topics.map((t) => { const s = tax.stages.find((x) => x.id === t.stage); return `| ${s.order} | ${s.id} | ${s.title} | https://smallbizacqs.com/guide/${s.id} | ${t.id} | ${t.title} | ${t.skill ? `\`${t.skill}\`` : `(none: ${t.exempt})`} |`; }).join('\n')}

## Skills that work across stages

| Skill | Kind | Covers |
|---|---|---|
${(tax.extra_skills ?? []).map((x) => `| \`${x.skill}\` | ${x.kind} | ${x.covers === 'router' ? 'any stage (entry point)' : `leaf \`${x.covers}\``} |`).join('\n')}

## How to pick the next one to three skills

1. Find the user's stage (the \`stage\` field in \`profile.yaml\`).
2. Within that stage, pick the topic that matches the job in front of them now, not the first row.
3. Add at most two more: the next topic in the same stage, or the first topic of the next stage if the current stage is nearly done.
4. Always offer \`grill-my-deal\` once there is a specific deal (stages 5 to 8) or a written search plan (stage 3).
`;

// ---- every skill ships the files it needs, because \`npx skills add\` installs only the skill folder:
// references/workspace.md (the workspace spec) and references/sources.md (the source cards it cites, with review dates)
const SOURCE_REF = /\b((?:sba-sop-50-10-[0-9-]+|ecfr|irs|uscis|sba|ftc|fcc|dol|eeoc|cfpb|census|usc|uspto|copyright|mn|google|healthcare|doj|eos|lifeline|stanford|sec|bizbuysell|acquire|flippa|trustmrr)-[a-z0-9]+(?:-[a-z0-9]+)*)\b/g;
const sourceIds = new Set(readdirSync(join(ROOT, 'data/sources')).map((f) => f.replace(/\.yaml$/, '')));
const spec = readFileSync(join(ROOT, 'workspace/SPEC.md'), 'utf8');
const perSkill = {};
const walkMd = (d) => readdirSync(d, { withFileTypes: true }).flatMap((e) => e.isDirectory() ? walkMd(join(d, e.name)) : e.name.endsWith('.md') ? [join(d, e.name)] : []);
for (const sk of skills) {
  const dir = join(skillsDir, sk.dir);
  perSkill[`skills/${sk.dir}/references/workspace.md`] = `<!-- Copied from workspace/SPEC.md by scripts/generate.mjs so the skill works when installed on its own. Don't edit here. -->\n${spec}`;
  const ids = new Set();
  for (const f of walkMd(dir)) {
    if (f.endsWith('references/sources.md') || f.endsWith('references/workspace.md')) continue;
    for (const [, id] of readFileSync(f, 'utf8').matchAll(SOURCE_REF)) if (sourceIds.has(id)) ids.add(id);
  }
  if (!ids.size) continue;
  const cards = [...ids].sort().map((id) => { const c = YAML.parse(readFileSync(join(ROOT, 'data/sources', `${id}.yaml`), 'utf8'));
    return `## ${id}\n\n- **Source:** ${c.title}${c.publisher ? `, ${c.publisher}` : ''}\n- **URL:** ${c.url}\n- **Supports:** ${c.proposition}\n- **Quote:** "${c.quote}"\n- **Checked:** ${c.accessed} · **Re-check by:** ${c.review_by}\n`; }).join('\n');
  perSkill[`skills/${sk.dir}/references/sources.md`] = `<!-- Generated by scripts/generate.mjs from data/sources/. Don't edit here. -->\n# Sources this skill cites\n\nEach entry gives the exact quote relied on and the date it was checked. If a **Re-check by** date has passed, or the rule is an SBA rule, tell the user it may have changed and to confirm the current version (for SBA rules, the current SOP 50 10 and their lender).\n\n${cards}`;
}

const out = {
  ...perSkill,
  'skills/buy-a-business/references/stage-map.md': stageMap,
  'README.md': readme,
  'llms.txt': llms,
  '.claude-plugin/marketplace.json': JSON.stringify(marketplace, null, 2) + '\n',
  '.claude-plugin/plugin.json': JSON.stringify(plugin, null, 2) + '\n',
  'gemini-extension.json': JSON.stringify(gemini, null, 2) + '\n',
};
const check = process.argv.includes('--check');
let stale = 0;
for (const [p, body] of Object.entries(out)) {
  const f = join(ROOT, p);
  if (check) { if (!existsSync(f) || readFileSync(f, 'utf8') !== body) { console.log(`stale: ${p}`); stale++; } continue; }
  mkdirSync(dirname(f), { recursive: true }); writeFileSync(f, body);
}
console.log(check ? (stale ? `${stale} generated file(s) are stale; run node scripts/generate.mjs` : 'generated files are current') : `wrote ${Object.keys(out).length} files · ${skills.length} skills · ${answered.length} answered questions`);
process.exit(stale ? 1 : 0);
